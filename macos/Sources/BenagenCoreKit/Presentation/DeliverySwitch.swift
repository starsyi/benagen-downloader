import Foundation

/// 一次「换交付码」的结果 —— 界面只需要知道这两件事。
///
/// ⚠️ 为什么要有这个类型（全局约束 C-6）：换码面板是视图，而"失败时该说什么"
///    与"成功了没有"都是**可断言的计算**。文案**不是**壳编的：它就是
///    `AppModel.message(of:)`（`CoreError` → 用户可见文案的**唯一**实现，约束 C-7）。
public enum DeliverySwitch: Equatable, Sendable {
    /// 换成功了，这是新的交付码。
    case switched(code: String)
    /// 没换成，这是**可直接显示给用户的那句话**（内核原文，或壳在"内核一个字都没说"时的说明）。
    case failed(message: String)

    // -----------------------------------------------------------------------
    // 主区那一行常驻提示（任务 2 复审重要 ②/③）
    //
    // ⚠️ **为什么结果必须由模型持有、由主区呈现，而不是只活在面板的 `@State` 里**：
    //    换码面板是**模态**的，而它的「取消」按钮**不被禁用**（面板关不关得掉，不该由
    //    一次网络请求决定 —— 见 `AppModel.switching` 的注释）。于是那次换码的结果会在
    //    面板销毁时**一起消失**，两个方向都会变成静默失效：
    //      - **失败方向**：内核那句原文是用户唯一能照着做点什么的话，面板一关就没了
    //        —— 约束 4 明禁的静默失效；
    //      - **成功方向**：请求照跑，成功时会把整批换掉并静默复位浏览位置与勾选面
    //        （`RootView.onChange(of: loadedCode)`）—— 用户看到的是"我按了取消，
    //        界面自己换了一批"，比他想象的更糟。
    //    所以结果落在 `AppModel.lastSwitchOutcome`，由 `RootView` 那一行提示区**常驻**呈现。
    // -----------------------------------------------------------------------

    /// 主区那一行提示要显示的文字。
    ///
    /// - 失败：**内核原文逐字**（约束 3），这里不加工、不加前缀。
    /// - 成功：`已换到批次 B`。
    ///   🔴 **这一句是壳自己写的用户可见文案**（约束 C-10/11 要求写明理由）：
    ///      内核**不会为一次成功的换码主动说话** —— 它回的是 JSON 字段（`code` 等），
    ///      没有一句可以照登的人话。而"界面自己换了一批"必须有个落点（见上面那段），
    ///      否则取消之后的那次成功换码在用户眼里就是一次**没有来源的界面变化**。
    ///      这句话只陈述一个**内核给的事实**（新批次的码就是它回的 `code`），
    ///      不添加任何判断或建议。
    public var noticeText: String {
        switch self {
        case .switched(let code): return "已换到批次 \(code)"
        case .failed(let message): return message
        }
    }

    /// 这一行说的是"没成"吗（视图据此选图标与颜色 —— 渲染分派）。**有单测**：
    /// 它不是顺手加的，而是"两种结果在界面上分得开"这条要求的落点。
    public var isFailure: Bool {
        if case .failed = self { return true }
        return false
    }
}
