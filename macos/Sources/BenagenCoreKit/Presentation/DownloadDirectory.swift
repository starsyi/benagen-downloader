import Foundation

// ---------------------------------------------------------------------------
// 可选下载目录的**纯计算**（阶段 E 规格 §2，任务 3）
//
// 下载目录只能经 **argv** 在内核启动时定（`--download-dir`，`core/src/main.rs:1678`），
// 协议里的 `set_settings` **没有**这个键（`core/src/settings.rs:32-47` 只有七个数值键）
// ⇒ "改目录"必然是**重启内核**。这个文件装的是那条链路上所有**可断言**的部分：
//
//   · `argument(for:)` —— **E-5 的判据**：该不该给内核传那个 flag；
//   · `confirmation(from:to:)` —— **E-6 的文案**（三条后果，逐条写明）；
//   · `check(_:)` —— 目录**能不能用**（不可写 / 不存在 ⇒ 在**确认之前**就报错并中止，§2.3）；
//   · `display(_:)` / `sectionNote` —— 设置窗口里那两句话。
//
// ⚠️ 视图只做绑定与渲染分派（E-7）：本文件里没有 `NSOpenPanel`、没有 `alert`。
//
// ---------------------------------------------------------------------------
// 🔴 层契约的**例外申报**（E-8 ①，最终审查顺手 4）
// ---------------------------------------------------------------------------
//
// `Presentation/` 那一层的契约是"**纯计算、不碰文件系统**"，而 `AppPreferencesStore`
// 的注释正拿这句话当"自己为什么放模块根"的理由（`AppPreferencesStore.swift:12-14`）。
// **本文件是那条契约的唯一例外**：[`check(_:)`] 调 `FileManager`（`fileExists` /
// `isWritableFile`）。两句话不能同时成立，所以把这个例外**申报在这里**：
//
//   · **为什么需要它**：规格 §2.3 要求"目录不可用 ⇒ **在确认对话框之前**就报错并中止"。
//     "这个位置存不存在 / 是不是文件夹 / 能不能写"**只能**问文件系统 —— 没有纯计算的
//     等价物（路径字符串上看不出来）。放到视图里也不行：那会把一条**判据**塞进
//     `Sources/BenagenDownloader/`，而这一层的规矩是"能写出断言的都归这里"（全局约束 8），
//     而且两个调用点（设置窗口那一段与将来的任何入口）就得各写一遍。
//   · **为什么可以接受**（代价如实记下）：它破的是"这一层不碰盘"这条**阅读契约**，
//     不是"这一层可断言"那条**测试契约** —— `check(_:)` 仍然是纯函数（同名输入同名输出、
//     没有状态、没有时钟），只是从**磁盘**取输入，所以它照样有单测
//     （`DownloadDirectoryTests` 里那四条边界，全部只碰 `temporaryDirectory`）。
//   · **诚实起见**：全 `Presentation/` 里**唯一调用** `FileManager` 的就是本文件的
//     `check(_:)` —— 逐字复核：
//     `grep -rn "FileManager" Sources/BenagenCoreKit/Presentation/`
//     的另一处命中是 `TransferRow.swift:399` 的一句注释（那里说的是"**别用**
//     `FileManager.homeDirectoryForCurrentUser`"），不是调用。
//     下一个要往这一层加"顺手读一下盘"的人：**别照抄这里** —— 例外只有一条，
//     就写在 `check(_:)` 这一个判据上。
// ---------------------------------------------------------------------------

public enum DownloadDirectory {
    // MARK: - 显示

    /// 内核默认目录的**人话形式**。
    ///
    /// ⚠️ **它只是显示，永远不进 argv**（E-5 禁的是"显式传一个与内核默认值相同的值"，
    ///    不是"不许告诉用户文件下到哪"）。后果的**量级**要看清：内核哪天改了默认值，
    ///    这句话会过时（顶多误导），而**不会**让文件下到别处去 ——
    ///    后者才是 E-5 要防的静默分叉，而它已经被 `argument(for:)` 的 `nil` 挡死了。
    public static let kernelDefaultDisplayPath = "~/Downloads/Benagen"

    /// 未配置时在设置窗口里显示的那一行。
    public static let defaultDisplay = "默认（\(kernelDefaultDisplayPath)，由内核决定）"

    /// 当前下载目录只读显示的文字。空串 = 未配置 ⇒ 说"默认"，而不是画一个空行
    ///（空行在界面上读起来与"这一行坏了"分不开）。
    public static func display(_ path: String) -> String {
        path.isEmpty ? defaultDisplay : path
    }

    /// 设置窗口里那一段的脚注。**说明"未配置"是什么意思** —— 它是本功能唯一
    /// 反直觉的地方（"没有设置"也是一种设置）。
    ///
    /// ⚠️ 最后那句是**网络盘的提示**（Ruling D3 的复核结论，最终审查重要 3）。
    ///    阶段 D 的裁定 D3 明写："下阶段若要做「可选下载目录」，这条要一起复核 ——
    ///    因为那正好会让用户有机会把目录指到网络盘"。**本阶段就是那个下阶段**：
    ///    在此之前"下载目录在本地盘上"是**结构上**成立的（硬编码 `$HOME/Downloads/Benagen`），
    ///    而今天用户一步操作就能把它指到 NFS/SMB 上 ⇒ 内核每次列目录 / 取树 /
    ///    加入下载都要**持着内核锁**对 `complete` 里每个路径 stat 一遍（`core/src/main.rs`
    ///    的 `recheck_complete_on_disk`），网络盘的 stat 是秒级 ⇒ 内核的同步读循环停摆。
    ///    形态是**变慢**、不是变错（裁定 D3 原文），所以**不改内核**（那是裁定），
    ///    只把这件事**说出来**（这一句 + `macos/README.md` 的已知限制那一节）。
    ///    🔴 这句话是**壳自己写的**（约束 3 的例外）：内核不会为一件它还没遇到的慢因说话。
    public static let sectionNote =
        "没有设置过时，壳**不指定**下载目录，由内核用它自己的默认值。"
        + "改变目录会立刻重启内核（正在跑的任务会停）。"
        + "请尽量选**本机磁盘**上的目录：网络盘（NFS / SMB）会让界面明显变慢。"

    // MARK: - E-5：该不该传 `--download-dir`

    /// **E-5 的唯一判据**：未配置 ⇒ `nil`（= 那个 flag 根本不出现；
    /// `CoreClient.coreArguments` 对 `nil` 不加参数）。
    ///
    /// ⚠️ **不许**改成"返回一个与内核默认值相同的路径"：那样只要内核改了默认值，
    ///    壳就会把用户悄悄带回老地方 —— 一次没有任何提示的分叉。
    public static func argument(for preferences: AppPreferences) -> String? {
        preferences.isConfigured ? preferences.downloadDir : nil
    }

    // MARK: - §2.3：这个目录能不能用

    /// 目录可用性检查。`nil` = 可以用；非 `nil` = **直接显示给用户**的那句话。
    ///
    /// ⚠️ 时机：**在确认对话框之前**（规格 §2.3）。等重启完才发现"这个文件夹不可写"，
    ///    用户已经为它停掉了一次正在跑的任务。
    ///
    /// ⚠️ 空串**直接放行**：它不是路径，是"回到未配置" —— 内核会用自己的默认值
    ///    并在启动时建它，壳无从检查，也不该替它猜。
    ///
    /// 🔴 这句话是**壳自己写的**（约束 3 的例外，理由写在这里）：内核**还不知道**
    ///    这件事（它还没被起起来），没有原文可登。而"选了一个不能写的目录"必须有落点
    ///    —— 否则用户会在重启之后看到引擎报一句他看不懂的错，或者更糟：什么都没看到。
    public static func check(_ path: String) -> String? {
        guard !path.isEmpty else { return nil }

        var isDirectory: ObjCBool = false
        guard FileManager.default.fileExists(atPath: path, isDirectory: &isDirectory) else {
            return "这个位置不存在：\(path)"
        }
        guard isDirectory.boolValue else {
            return "这是一个文件，不是文件夹：\(path)"
        }
        guard FileManager.default.isWritableFile(atPath: path) else {
            return "这个文件夹不可以写入（没有权限）：\(path)"
        }
        return nil
    }

    // MARK: - E-6：确认文案

    /// 改目录之前必须让用户看到的那段话。**三条后果逐条写明**（E-6）。
    ///
    /// ⚠️ 第 2 条的措辞是**「新目录里没有记录的文件会重新校验」**，不是"一定会重新校验"
    ///    （规格 §2.3）：用户完全可能选了一个**已经有 `.benagen-state.json` 的目录**
    ///    （例如换回旧目录），那时内核会把状态读回来（`core/src/state.rs:18-21`、
    ///    `main.rs:202`），一个字节都不用重新校验。
    ///    ⚠️ **别把它"说全"**：一句断言式的"所有文件都会重新校验"会让用户为一件
    ///    不会发生的事做决定 —— 而这条文案的全部价值就是让他知道**会发生什么**。
    public static func confirmation(from current: String, to target: String) -> String {
        """
        下载目录将从「\(display(current))」改为「\(display(target))」。

        改完会立刻重启内核，三条后果：
        1. 正在跑的任务会停（内核重启），没传完的文件要重新点一次下载；
        2. 新目录里没有记录的文件会重新校验（内核的状态文件就在下载目录里）；
        3. 旧目录里的文件不会被删、也不会被搬走。
        """
    }
}

// ---------------------------------------------------------------------------
// 一次「改下载目录」的结果
// ---------------------------------------------------------------------------

/// 界面只需要知道这三件事。
///
/// ⚠️ 与 `DeliverySwitch` 同一个形状、同一个理由：结果要**可断言**，而"该说什么"
///    不该由视图现编（E-7）。`.failed` 里那句可能是内核原文（内核重启失败时那句是
///    壳在 `restartKernel` 里写的说明），也可能是写盘失败的原文 —— 两种都**照登**。
public enum DownloadDirChange: Equatable, Sendable {
    /// 改成了：偏好已落盘、内核已按**新**目录重启。
    case changed(dir: String)
    /// 目标与当前一致 ⇒ **什么都没做**（内核没重启、正在跑的任务不受影响）。
    ///
    /// ⚠️ 这一格不是装饰：E-6 的确认文案说"正在跑的任务会停"，而**没改**的时候
    ///    停掉用户的任务是纯损失 —— 用户在面板里选中**同一个目录**是很容易发生的
    ///    （尤其是"我只是想看看现在用的是哪个"）。
    case unchanged(dir: String)
    /// 没改成：这是**可直接显示给用户的那句话**。
    case failed(message: String)

    // -----------------------------------------------------------------------
    // 🔴 为什么把「标题」与「路径」拆成两个属性（阶段 E 修复波，**一条真实的布局事故**）
    //
    // 现场：改完下载目录、内核按新目录重启之后，**文件页底栏**（全选 / 全不选 /
    // 下载选中）与**侧边栏的批次摘要**一起从窗口里消失；把窗口拉高、或者点一下
    // 「恢复默认」，两处又都回来了。四条观测（窗口只有一个、拉高就好、整体上拖没用、
    // 恢复默认就好）指向同一件事：**内容比窗口高，锚在底边的东西被裁掉了**。
    //
    // 根因就在下面 `noticeText` 的**成功那一支**：它把**用户选的完整路径**塞进了
    // 一条**常驻**回执（`RootView` 的 `downloadDirBar`，它必须活过设置窗口 —— 理由写在
    // 那边），而那一行原先没有行数上限、还带 `fixedSize(vertical:)`（允许折行）
    // ⇒ **路径越长这一行越高**。路径是**外部文本**，它的长度不该由界面来控制，
    // 更不该由它来决定"窗口内容有多高"。恢复默认那一句**不含路径、固定短**，
    // 所以它一按就恢复 —— 这正好解释了观测 ④。
    //
    // 修法就是把这件事在**值**这一层说清楚（视图不单测，所以判据必须落在这里）：
    //   · `headline`  —— **固定短的标题**，**任何路径下逐字相同**（回归守卫见
    //     `DownloadDirectoryTests.theHeadlineIsFixedNoMatterHowLongThePathIs`）；
    //   · `pathDetail` —— 路径**单独一个值**，由视图渲染成自己的一行
    //     （`lineLimit(1)` + 中间截断 + 悬停看全文）⇒ 这条提示的高度**与路径长短无关**。
    //
    // ⚠️ **`noticeText` 一个字都没改**（逐字由 `DownloadDirectoryTests` 钉着）：
    //    改措辞不在本次修复的范围里。
    //    ⚠️ 但**界面上不再显示它了**（第 2 轮起）：两个落点渲染的都是 `headline` +
    //    `pathDetail` 那两行 —— 它现在只是**防回归的锚**（完整说明见它自己的文档注释）。
    //    它仍然**由这两个属性组合而成** —— 有路径就是把路径填进那句话，没路径则
    //    标题本身就是全文（两支不可能分叉）。
    // -----------------------------------------------------------------------

    /// 成功那支的**固定标题**（不含路径）。**只在 `headline` 里用一次。**
    ///
    /// ⚠️ 别往这里塞路径、也别塞批次号 / 时间戳之类**长度不受控**的东西：
    ///    这个属性存在的全部意义就是"**长度固定**"（见上面那段）。
    private static let changedTitle = "下载目录已改（内核已按新目录重启）"

    /// 恢复默认那支的**固定全文**（本来就短，没有路径可拆）。
    private static let restoredDefault = "已恢复默认下载目录（内核已按默认目录重启）"

    /// **这条回执的第一行**：固定短的标题，**任何情况下都不含路径**。
    ///
    /// ⚠️ `dir` 在这里**只用来区分"改了"与"恢复默认"两个格子**，绝不参与拼字符串 ——
    ///    这是本次布局事故的回归判据。要显示路径请用 `pathDetail`。
    ///
    /// ⚠️ `.failed` 那一格**照登原文**（约束 3）：那可能是内核的失败原因，也可能是
    ///    写盘失败的系统错误文本，两者都**不许**加工、**不许**截断成"标题"
    ///    （"失败原文必须完整可见"是硬要求）。它同样是**外部文本**，
    ///    高度由**视图**那边统一封顶 —— 但封的是**高度、不是内容**：
    ///    `Views/ResidentNotice.swift` 的 `BoundedNoticeArea`（放得下按自然高显示、
    ///    放不下就钉在 48pt 上**可滚动**），**全文始终都在**，没有截断。
    ///    ⚠️ 别在值这一层替它做长度限制：那是**丢证据**，不是排版。
    public var headline: String {
        switch self {
        case .changed(let dir):
            // 🔴 这两句是**壳自己写的**（约束 3 的例外）：内核不会为一次成功的重启
            //    主动说话，它回的是 argv 与 JSON 字段。而"我按了确认之后发生了什么"
            //    必须有个落点，否则那个确认框就像按了个寂寞。
            return dir.isEmpty ? Self.restoredDefault : Self.changedTitle
        case .unchanged:
            return "下载目录没有变化，没有重启内核"
        case .failed(let message):
            return message
        }
    }

    /// **要单独占一行显示的路径**；`nil` = 这条回执没有路径行可显示。
    ///
    /// ⚠️ 只有 `.changed` 且 `dir` **非空**时才有值：空串是"恢复默认"，它不是路径
    ///    （画一个空行在界面上读起来与"这一行坏了"分不开 —— 同 `display(_:)` 的理由）。
    ///    其余两支（`unchanged` / `failed`）**不许拆**：失败那句是内核/系统的原文，
    ///    拆开就等于重排用户的证据（约束 3）。
    ///
    /// ⚠️ 这里**原样**返回路径：截断是**视图**的事（`truncationMode(.middle)` +
    ///    `.help`），值这一层不许自己动手 —— 一旦在这里截，`.help` 就只能显示截过的
    ///    那一段，"悬停看完整路径"这条出口就没了。
    public var pathDetail: String? {
        guard case .changed(let dir) = self, !dir.isEmpty else { return nil }
        return dir
    }

    /// 这条回执**完整的一句话**。**逐字保持布局事故修复前的样子**。
    ///
    /// 🔴 **界面上已经不显示它了**（第 2 轮起）：两个落点（主区那条常驻行与设置窗口里
    ///    那一段）渲染的都是 `headline` + `pathDetail` 那**两行** —— 把含完整路径的整句
    ///    铺在一行里，正是那次"底部整条被顶出窗口"的根因。
    ///    `grep -rn "\.noticeText" macos/Sources/` 现在只会命中 `DeliverySwitch.noticeText`
    ///    （另一个类型）—— **`DownloadDirChange.noticeText` 在 Sources 里零引用**。
    ///
    /// 那它为什么还在、还是 `public`：
    ///   · 它是**防回归的锚**：四支的措辞被 `DownloadDirectoryTests` 逐字钉着
    ///     （成功改目录 / 恢复默认 / 没变化 / 失败原文），谁把文案改一个字就红；
    ///     而"这两行必须能拼回原来那句话"这件事靠它守（有路径 ⇒ 路径进那句话）。
    ///   · 它是这个结果**完整的一句话**，属于 Kit 对外的语义。一次**布局**修复
    ///     不该顺手缩小公开 API（删了它，将来任何一个"想显示整句"的调用点
    ///     就只能自己拼字符串）。
    ///
    /// ⚠️ 它**由 `headline` 与 `pathDetail` 组合而成**，不是另抄一份字面量：
    ///    没路径 ⇒ 标题就是全文（这一支两处不可能分叉）；有路径 ⇒ 把路径填进那句话。
    ///    ⚠️ 但**别指望这条来守"标题里混进了路径"**：这一支用的是 `pathDetail`、
    ///    根本不经过 `headline`，所以标题被改坏时它照样是绿的 ——
    ///    守那件事的是 `theHeadlineIsFixedNoMatterHowLongThePathIs`
    ///    （实测：把路径塞回 `headline`，那条红 4 个断言，这条一个都不红）。
    public var noticeText: String {
        switch self {
        case .changed:
            guard let path = pathDetail else { return headline }
            return "下载目录已改为 \(path)（内核已按新目录重启）"
        case .unchanged, .failed:
            return headline
        }
    }

    /// 这一行说的是"没成"吗（视图据此选图标与颜色）。**有单测**。
    public var isFailure: Bool {
        if case .failed = self { return true }
        return false
    }
}
