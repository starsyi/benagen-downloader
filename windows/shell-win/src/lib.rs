//! `shell_win` —— Windows 壳的**库**那一半（D1）。
//!
//! ## 为什么壳要有 lib target
//!
//! ① bin target 里"没被 `main` 用到的 `pub` 项"**会**触发 `dead_code` 告警，
//!    而本仓库是零告警口径。放进 lib 之后公开面不算死代码 ⇒ 任务可以**自底向上**
//!    逐个加模块、每一步都编译干净，**不需要**任何临时 `#![allow(dead_code)]`
//!    （那种"临时的"允许从来不会有人记得删）。
//! ② 集成测试（`tests/`）能直接 `use shell_win::…`，不必起真进程。
//!
//! ⚠️ **本文件是模块清单的唯一属主**：加一个模块就加一行 `pub mod`。
//!    （一个建了却**没被声明**的 `.rs` 文件，它的测试一条都不会跑，而 `cargo test`
//!    照样全绿 —— `windows/scripts/test.sh` 的"空跑绿灯判为失败"是同一件事的第二道网。）
//!
//! ## ⚠️ Tauri 那一代删掉了什么（规格 §1.2：第二代传输层整体作废）
//!
//! 从模块表里去掉的有：`assets`（内嵌静态资源）、`browser`（找系统浏览器）、
//! `envelope`（HTTP 响应信封，**搬去 `shell-core`** 是任务 7 的事）、
//! `heartbeat`（心跳看门狗）、`server`（本地 HTTP 服务）、`token`（一次性凭证）。
//! 它们废于**同一件事**：Tauri 自己就是宿主（前端由 `tauri://localhost` 提供、
//! 只有本进程的 webview 能调 `invoke`）⇒ **本代不监听任何端口、没有凭证、
//! 没有心跳、没有看门狗、也没有别的进程能调进来**（规格 §3.3）。
//! 原文与它们的用例都在 git 历史里（本次提交的父提交）。

