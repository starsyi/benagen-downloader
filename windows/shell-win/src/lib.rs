// ⚠️ **它进 lib 是因为那两份许可全文必须内嵌进交付形态**（W-5 / 裁定 RR）：本模块用
//    `include_str!` 把 GPLv2 与 OFL-1.1 两份**全文**编进二进制，而"编进二进制"这件事
//    **只在有代码引用它的那个 target 上成立** —— 阶段 A 有一度它一个 target 都不编
//    ⇒ 交付形态的 exe 里就没有那两份全文了（`build_windows.sh` 第 5 步那两根 sha256 的
