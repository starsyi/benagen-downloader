#!/usr/bin/env bash
#
# windows/scripts/check_wire_fixtures.sh —— **夹具漂移判据**：入库的那份载荷夹具
# 必须与"现在从 Rust 倒出来"的那份**逐字节相同**。
#
#    bash windows/scripts/check_wire_fixtures.sh
#
# 它由 `windows/scripts/test.sh` 第 0.7 步调用（**按需单跑也可以**）。
#
# ---------------------------------------------------------------------------
# 它为什么存在（R-56 / R-54：**做过一次的事不等于被守住了**）
# ---------------------------------------------------------------------------
#   任务 10 的第 2 轮把前端那套无头验收的载荷改成了**从 Rust 生成**
#   （`windows/scripts/make_wire_fixtures.sh` → `frontend-stub/wire-fixtures.json`），
#   修的是一类真实的病：**手抄的夹具与前端代码会犯同一个错**，于是几十条断言全绿、
#   而真载荷下界面是坏的（那一轮抓到的两条 Critical 就是这么来的）。
#
#   ⚠️ 但"生成了一次"**不是**"守住了"：那份夹具是**入库**的，
#      一旦有人改了 wire 形状（`api::tree` / `api::enqueue` / `api::state`）而忘了重跑生成命令，
#      它就会**悄悄过期** —— 前端那套验收继续对着**旧的形状**全绿，
#      于是同一个病换个入口再来一次。**没有这条判据时，它过期的样子与"它是对的"一模一样。**
#
#   本脚本就是那条判据：**重新生成一份，与入库那份逐字节比**。
#
# ---------------------------------------------------------------------------
# 判据（fail-closed）
# ---------------------------------------------------------------------------
#   ① 入库那份**必须在场**（缺席 ⇒ 红：那不是"没有夹具"，是"这一屏的验收没有对象"）；
#   ② 重新生成一份（走 `make_wire_fixtures.sh`，**同一份代码、同一条命令**），
#      与入库那份 `diff` —— 有任何差异 ⇒ **红**，并把差异逐行打出来。
#
#   ⚠️ 比对用 `diff`（不是"比 sha 再说"）：**红了要能看懂哪里变了**。
#      sha 只能告诉你"变了"，而这条判据的读者是"改了 wire 形状的那个人"。
#
# ---------------------------------------------------------------------------
# 退出码（与 `check_frontend_copy.sh` / `check_design_fonts.sh` 同一套）
# ---------------------------------------------------------------------------
#   0 = 判据通过（两份逐字节相同）
#   1 = 环境问题（生成命令跑不起来 —— W-2：大声说 + 给可执行的补救）
#   2 = 用法错误（给了参数）
#   3 = **判据没过**（夹具过期了 / 不在场）
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
COMMITTED="$REPO/windows/scripts/frontend-stub/wire-fixtures.json"
maker="$REPO/windows/scripts/make_wire_fixtures.sh"

die() { echo "错误：$*" >&2; exit 1; }
note() { echo "==> $*" >&2; }

# ---------------------------------------------------------------------------
# 参数：**一个都不认**（同 `check_frontend_copy.sh` 的纪律：透传一个打错的 flag
# 会让脚本以一个"看起来像失败"的退出码收场，而根因是打错了字）
# ---------------------------------------------------------------------------
while [ "$#" -gt 0 ]; do
  echo "check_wire_fixtures.sh: 不认识的参数：$1" >&2
  echo "check_wire_fixtures.sh: 本脚本不接受任何参数（生成命令与比对对象都写死在本文件里）。" >&2
  exit 2
done

# ---- ① 入库那份必须在场 ------------------------------------------------------
# ⚠️ 缺席**不是**"这一条跳过"：夹具不在场 ⇒ 前端那套无头验收**没有对象**，
#    而那正是本判据要防的那件事的极端形态（这里直接红，并把补救写清楚）。
[ -f "$COMMITTED" ] || die "找不到 $COMMITTED —— 载荷夹具不在场。
      => 这不是\"跳过\"：它是前端那套无头验收（含任务 11/12/13 复用）的**唯一**载荷来源，
         缺了它那套验收就没有对象。
      补救：bash windows/scripts/make_wire_fixtures.sh"

[ -f "$maker" ] || die "找不到 $maker —— 生成命令不在场，判据无从判起。"

# ---- ② 重新生成一份，与入库那份逐字节比 --------------------------------------
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT
fresh="$tmp_dir/wire-fixtures.json"

note "重新生成一份夹具（bash windows/scripts/make_wire_fixtures.sh <临时路径>）"
# ⚠️ 生成命令自己失败 ⇒ **必须红**：一个"因为生成器跑不起来所以通过"的判据，
#    与没有判据无法区分（同 `test.sh` 里那条"空跑绿灯判为失败"的纪律）。
if ! bash "$maker" "$fresh" >&2; then
  die "生成命令失败了（退出码非零）—— 判据判不了，这不是\"通过\"。
      先修生成器：cargo run -q -p shell-core --example dump_wire_fixtures -- <路径>"
fi
[ -s "$fresh" ] || die "生成命令跑完了，但产物是空的 —— 这不是\"通过\"。"

if diff -u "$COMMITTED" "$fresh" > "$tmp_dir/diff.txt"; then
  note "判据通过：入库的夹具与现在从 Rust 倒出来的那一份**逐字节相同**（$(wc -c < "$COMMITTED" | tr -d ' ') 字节）"
  exit 0
fi

# ---- 红了：把差异逐行打出来（有界）+ 说清补救 ---------------------------------
# ⚠️ 差异行数**有上界**（再多就把真信息淹了）；总数仍然写在标题里。
MAX_LINES=40
total="$(wc -l < "$tmp_dir/diff.txt" | tr -d ' ')"
# ⚠️ "只显示前 N 行"那句话**先算好**，不要在 `echo "…$(…)"` 里用 `&&` 现拼：
#    那种写法在 `set -e` 下的退出码是条出名的暗坑（判据脚本自己踩进去最难查）。
shown=""
if [ "$total" -gt "$MAX_LINES" ]; then
  shown="，下面只显示前 $MAX_LINES 行"
fi
{
  echo ""
  echo "夹具漂移判据没过：入库的那份载荷夹具**已经过期**。"
  echo "    $COMMITTED"
  echo "  与现在从 Rust 倒出来的那一份有差异（diff 共 $total 行${shown}）："
  echo ""
  sed -n "1,${MAX_LINES}p" "$tmp_dir/diff.txt" | sed 's/^/      /'
  echo ""
  echo "  为什么这条判据存在：前端那套无头验收（以及任务 11/12/13 各自那一套）"
  echo "  吃的是这份夹具。它过期之后，那套验收会**对着旧的线上形状全绿** ——"
  echo "  而「夹具遮住了真实破坏」正是任务 10 第 2 轮修掉的那个病。"
  echo ""
  echo "  补救（二选一）："
  echo "    · 这次改动**确实**要改线上形状 ⇒ 重跑生成命令并**把新夹具一起提交**："
  echo "        bash windows/scripts/make_wire_fixtures.sh"
  echo "      同时确认前端读的格子名跟着改了（夹具就是那条对照表）。"
  echo "    · 你没打算改线上形状 ⇒ 上面 diff 里那几行是**意外改动**，回头查它。"
  echo ""
  echo "  ⚠️ 不要手工编辑那份 JSON：它是生成物，手改之后下一次生成还会红（那正是本判据的用法）。"
} >&2
exit 3
