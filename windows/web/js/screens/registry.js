// registry.js —— **屏幕注册表**，以及"一个屏长什么样"的**接口契约**。
//
// 任务 10/11/12 是三个**彼此独立**的屏。它们能并行的前提，就是这个文件把边界钉死：
// 每一屏只知道自己那一块，谁都不用读别人的代码。**契约在本文件里只有一份。**
//
// ---------------------------------------------------------------------------
// 🔴 屏的接口（任务 10/11/12 照这里写，别自己发明第二套）
// ---------------------------------------------------------------------------
//
//   // windows/web/js/screens/<name>.js
//   export const id = "<name>";                 // 与下面 SCREENS 的键一致
//   export function mount(el, ctx) {            // el = 壳给的宿主（#page 里的一个 div）
//     // ① 只在这里建 DOM（从 index.html 的 <template> 克隆，或 h() 造）
//     // ② 只在这里绑事件
//     // ③ 其余时间什么都不做
//     return {
//       render(payload) { /* 载荷 → DOM。**不许建新的事件、不许发请求** */ },
//       unmount() { /* 解绑全局事件 / 停本屏自己的定时器 */ },
//
//       // ⚠️ **可选**（没写它 = 这一屏没有"下载"这个动作）
//       toolbarDownload() {
//         // 返回 null | { title: string, enabled: boolean, run(): void }
//       },
//
//       // ⚠️ **可选**（没写它 = 这一屏不往侧栏报计数）
//       navBadge() {
//         // 返回 { section: string, count: number }
//       },
//     };
//   }
//
// ---------------------------------------------------------------------------
// 🔴 `toolbarDownload()` —— 工具栏那颗下载按钮的**唯一**来源（任务 13 加）
// ---------------------------------------------------------------------------
// 它存在的理由是一次**真机验收**：`setDownloadEnabled` / `setDownloadTitle` 的调用点
// 曾经各为 0 ⇒ 工具栏那颗按钮**永远停在 HTML 里的 `disabled`、标题那一格永远是空的**
// —— 即"**一个禁用且没有文字的按钮**"。而人类伙伴点它的时候，期待的是 macOS 的行为：
// 那颗按钮的文案是 `DownloadTargets::button_title(selection)`（**空勾时它换一句话说，
// 不是变灰**），点它 = 对**当前勾选面**执行下载。
//
// 契约（**只有这一份**，`app.js` 与各屏都照这里写）：
//
//   · 壳每一拍问**当前那一屏**要一次这个描述符，并用它的 `title` / `enabled`
//     驱动工具栏那颗按钮（`shell.setDownloadAction`）；
//   · `title` **必须**是 Rust 给的那一句（`DownloadTargets::button_title` 经
//     `tree()` 的 `action.button_title` 下来）。屏**不许**自己拼、也不许兜底一个
//     「下载」—— 空串就是不显示（同 `shell.setDownloadAction` 的注释）。
//   · 返回 `null` ⇒ 壳把那一颗**禁用且清空文字**。`null` 的含义是
//     "**这一屏没有下载这个动作**"，**不是**"这一屏暂时没有选中项"——
//     后者是 `button_title` 的另一个分支，由 Rust 说，不由屏说。
//   · `run()` 由**屏**实现：只有它知道勾选面在哪（壳不知道，也不许猜）。
//   · **没写这个方法**（`undefined`）与返回 `null` **同义**。所以
//     `empty.js` / `verify.js` 一个字都不用改：校验页本来就没有下载动作。
//
// ⚠️ **不许在 `shell.js` 里给某一块屏开特例**（"如果这一屏是 verify 就……"）：
//    那样"这一屏有没有下载动作"就有了两个真相源，而第二个（壳里那个）会在
//    下一屏加进来时**悄悄过期**。判据在屏自己身上，壳只负责问。
//
// ⚠️ **已知的时延（如实记账）**：壳每拍（`state` 的 1 s 节拍）问一次，所以在屏里
//    勾了一项之后，工具栏那句话**最多晚一拍**才换。macOS 是即时的。
//    收窄它要一条"屏 → 壳"的推送通道，而契约第 1 条明禁屏调壳级 setter ——
//    本任务**不做**，如实记在报告里。
//
// ---------------------------------------------------------------------------
// 🔴 `navBadge()` —— 侧栏那颗未完成计数徽标的**唯一**来源
// ---------------------------------------------------------------------------
// 它与 `toolbarDownload()` 是**同一个形状**（壳问、屏答、壳摆位置），加它的理由也是
// 同一种**跨模块漏接**：`shell.setNavBadge` 与三个 `#badge-*` 早就备好了，
// 而**调用点各为 0** ⇒ 三个徽标**永远是 `hidden`**（macOS 上那是"去那一屏看看"
// 的唯一提示，而四块屏各自的验收都看不见壳这一格）。详见 `app.js:syncNavBadges`。
//
// 契约（**只有这一份**）：
//
//   · 壳每一拍问**当前那一屏**要一次 `{ section, count }`，收下之后喂给
//     `shell.setNavBadge`（`0` = 这一格不渲染，同 macOS 的 `.badge(0)`）；
//   · `count` **必须**是载荷里 Rust 算好的那一格（`transfers()` 的 `badge_count` /
//     `verify()` 的 `badge_count`，两条判据都在 `presentation::verify_summary::SidebarBadge`）。
//     屏**不许**自己数（"哪些算未落定/未通过"一旦有第二份实现，症状是
//     "侧栏徽标上的数与那一屏里看得见的东西对不上"，而**不会有任何东西变红**）；
//   · `section` 是这一步报的是哪个分区（`shell.js:SECTIONS` 的成员）——
//     壳把它记在**自己那一份**上，于是切走之后那颗徽标**还在**；
//   · **没写这个方法**与 `count: 0` 同义（`empty.js` 一个字都不用改）。
//
// ⚠️ **什么时候会旧（与 macOS 逐字同源，如实记账）**：每一个数只有**那一屏的载荷**
//    才有，而那一屏的节拍只在它可见时跑（规格 §3.5）⇒ 徽标反映的是
//    "最后一次看到那一屏时的样子"。macOS 也是这样（`AppModel.transfers` /
//    `AppModel.verify` 只在各自那一屏可见时被刷新）。**换批时壳会把三个数一起清零**
//    （`app.js:tickState`），所以不会出现"上一批的计数挂在这一批上"。
//
// 三条不许越过的线：
//
// 1. **不许碰壳**（`#nav` / `.toolbar` / `#notices` / `#batch-summary`）。
//    需要壳上多一个元素时，改 `js/shell.js` 并在报告里点名 —— 落在屏文件里的
//    壳元素**只在切到别的屏时**才消失，而那时已经没人记得它当初为什么在那儿。
//
// 2. **不许自己 `invoke`**：一律走 `ctx.call`（唯一的后端接触面，`js/invoke.js`）。
//    绕过它 = 绕过"失败原文逐字透传"那条唯一实现。
//
// 3. **不许有定时器**：节拍一律挂在 `ctx.poller` 上（`js/poll.js`），
//    并且**只在屏可见时**跑。屏自己的 `setInterval` 会在切走之后继续打内核，
//    而那种请求**没有任何界面会显示它**（典型的静默负载）。
//
// `ctx` 里有四样东西（**只有这四样**，别往里加"顺手带一个"的东西）：
//   · `call`    —— 后端接触面（`js/invoke.js`）
//   · `CMD`     —— 命令名表（同上）
//   · `poller`  —— 节拍器（`js/poll.js`）。除了 `start` / `stop`，
//                  还有 `pollNow()`：某个用户动作改了会话之后补一拍，
//                  免得要等一整秒的节拍才看得见反应。
//   · `shell`   —— 壳（`js/shell.js`）。⚠️ **只读用途**：屏可以读
//                  `shell.getSection()` 判断"我是不是当前这一屏"，
//                  **不许**调 `setBatchSummary` / `setNotices` 那类壳级 setter ——
//                  那些是 `app.js` 的路由职责，屏调了就会与轮询抢同一个槽位。
//
// ---------------------------------------------------------------------------
// 注册表
// ---------------------------------------------------------------------------

import * as empty from "./empty.js";
import * as files from "./files.js";
import * as transfers from "./transfers.js";
import * as verify from "./verify.js";

/**
 * 屏 id → 模块。
 *
 * ⚠️ **任务 10/11/12 各加一行 `import` 与一个键**（键名与 `shell.js:SECTIONS`
 *    的分区名一致：`files` / `transfers` / `verify`）：
 *
 *     import * as files from "./files.js";           // 任务 10
 *     import * as transfers from "./transfers.js";   // 任务 11
 *     import * as verify from "./verify.js";         // 任务 12
 *
 *     ⚠️ 这三行是**示例**，任务 10/11/12 各自加自己那一行 + 下面表里自己那一项。
 *        文件名就叫 `<屏名>.js`（`files` / `transfers` / `verify`），
 *        **不要**另起如 `filebrowser.js` 的名字 —— 计划里早期版本那样写过，已订正。
 *
 * ⚠️ **不要**改成"动态 import 的字符串表"：ES 模块的静态 `import` 会让
 *    "屏文件不存在"变成**构建/加载期**就看得见的错误，而动态 import 会把它推迟到
 *    用户切到那一屏的那一刻（那时窗口里只会有一次静默的失败）。
 */
const SCREENS = new Map([
  ["empty", empty],
  // 任务 10：文件页（`shell.js:SECTIONS` 的第一项）。
  ["files", files],
  // 传输列表屏（任务 11）。⚠️ 它是**唯一**按 200 ms 轮询的一屏
  //（`TransferListPoll::INTERVAL_NANOSECONDS`），节拍挂在 `ctx.poller` 上、
  // 且只在它挂载着（= 可见）的时候跑 —— 见 `screens/transfers.js` 的文件头。
  ["transfers", transfers],
  // 校验结果屏（任务 12）。⚠️ `rows` **恒 6 条**（含计数为 0 的类）—— 那是 Rust 的判据，
  // 这一屏只负责把六条画出来（含「0 项」）。
  ["verify", verify],
]);

/** 取一屏的模块；没注册过 ⇒ **抛出**（不返回 undefined 让它在下游变成一句 `xx is not a function`）。 */
export function screenFor(id) {
  const mod = SCREENS.get(id);
  if (!mod) {
    // 诊断（不是界面文案）：这是"程序自己坏了"，而它的补救是明确的 —— 见下面那句。
    // ⚠️ 措辞是**挑过的**，别顺手把「注册」改回来：这句话**会渲染**（`app.js:applyRoute`
    //    把它挂到常驻提示行上），而内嵌字体子集里没有「册」这个字 —— 写成
    //    「前端没有注**册**名为…」的后果是一个**豆腐块**，而它出现的那一刻恰恰是
    //    "加载成功之后主区一片空白、用户最需要读懂为什么"的那一刻。
    //    （`.js` 从来不在字体覆盖判据的扫描面里，所以这件事在任务 10b 之前**没有任何
    //      东西会变红** —— 现在由 `test.sh` 第 0.6 步守着。）
    throw new Error(
      `前端没有名为「${id}」的屏。`
        + "若这是任务 10/11/12 的屏，检查 js/screens/registry.js 的 SCREENS 里有没有加它那一行；"
        + "若这是路由算出来的 id，检查 js/render.js:routeOfState 与 shell.js:SECTIONS 是否一致。"
    );
  }
  return mod;
}

/** 已注册的屏 id（给诊断与测试用）。 */
export function screenIds() {
  return [...SCREENS.keys()];
}
